import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const origin = process.argv[2] || 'http://127.0.0.1:8080';
const destination = process.argv[3] || 'docs/agent-work/evidence/P2-r2/local';
await mkdir(destination, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader'] });
const checks = [], errors = [];
const record = (name, detail = true) => { checks.push({ name, detail }); console.log('PASS ' + name); };
const screenshot = (page, name) => page.screenshot({ path: destination + '/' + name + '.png', fullPage: false });
const world = page => page.locator('[data-focused-island]');
const image = (page, id) => page.locator('[data-island="' + id + '"]');
const loaded = async page => page.waitForFunction(() => [...document.querySelectorAll('[data-island] img')].length === 4 && [...document.querySelectorAll('[data-island] img')].every(i => i.complete && i.naturalWidth > 0));
const waitIdle = page => page.waitForFunction(() => document.querySelector('[data-moving]')?.dataset.moving === 'false');
const layout = async page => {
  const result = await page.evaluate(() => ({ viewport: innerWidth, scrollWidth: document.documentElement.scrollWidth, canvas: document.querySelectorAll('canvas').length, navLinks: [...document.querySelectorAll('header nav a')].map(a => ({ text: a.textContent, visible: a.getBoundingClientRect().height >= 44 })) }));
  assert.equal(result.scrollWidth, result.viewport); assert.ok(result.navLinks.every(i => i.visible));
  return result;
};
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await desktop.newPage();
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(origin + '/', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('canvas').count(), 0);
  assert.equal(await page.locator('img[src="/media/avatar-poster.png"]').count(), 0);
  const title = await page.locator('h1').boundingBox(), connect = await page.getByRole('button', { name: /^CONNECT/ }).boundingBox();
  assert.ok(Math.abs(title.x + title.width/2 - 720) < 2); assert.ok(Math.abs(connect.x + connect.width/2 - 720) < 2);
  await screenshot(page, 'welcome-night-1440'); record('centered welcome; no avatar', await layout(page));
  await page.getByRole('button', { name: /^CONNECT/ }).click();
  await page.waitForFunction(() => document.querySelector('[data-stranger]') && getComputedStyle(document.querySelector('[data-stranger]')).opacity > .95);
  await page.waitForFunction(() => document.querySelector('canvas') || document.querySelector('img[src="/media/avatar-poster.png"]'));
  await screenshot(page, 'greeting-night-1440'); record('avatar appears only after CONNECT');
  await page.waitForURL('**/hub/', { timeout: 15000 }); await loaded(page); await waitIdle(page);
  await screenshot(page, 'diamond-night-1440');
  const initial = await page.locator('[data-slot]').evaluateAll(nodes => nodes.map(n => { const b=n.getBoundingClientRect(); return { slot:n.dataset.slot, x:b.x+b.width/2, y:b.y+b.height/2 }; }));
  const slots = Object.fromEntries(initial.map(p => [p.slot,p]));
  assert.ok(Math.abs(slots.front.x - slots.back.x) < 1);
  assert.ok(Math.abs(slots.left.x + slots.right.x - 1440) < 1);
  assert.ok(Math.abs(slots.left.y - (slots.front.y+slots.back.y)/2) < 1);
  record('four positions form a diamond', initial);
  await image(page,'sky').click(); await page.waitForURL('**/works/themes/sky/');
  assert.equal(await page.locator('h1').innerText(),'天空之城');
  await page.goBack(); await page.waitForURL('**/hub/'); await loaded(page); await waitIdle(page);
  assert.equal(await world(page).getAttribute('data-focused-island'),'sky');
  record('initial Sky roundtrip retains the next orbital animation');
  let box = await image(page, 'ancient').boundingBox();
  await page.mouse.move(box.x + box.width*.25, box.y + box.height*.5);
  await page.waitForTimeout(100); assert.equal(await world(page).getAttribute('data-focused-island'),'sky');
  await page.mouse.move(20,820); await page.waitForTimeout(330);
  assert.equal(await world(page).getAttribute('data-focused-island'),'sky'); record('short hover cancels without switching');
  box = await image(page,'ancient').boundingBox();
  await page.mouse.move(box.x + box.width*.25, box.y + box.height*.5);
  await page.waitForFunction(() => document.querySelector('[data-focused-island]')?.dataset.focusedIsland === 'ancient');
  assert.equal(await world(page).getAttribute('data-moving'),'true');
  await page.waitForTimeout(500); await screenshot(page, 'orbit-midflight-1440');
  await waitIdle(page); await page.waitForTimeout(450);
  assert.equal(await world(page).getAttribute('data-focused-island'),'ancient'); record('delayed curved motion; stationary pointer stays stable');
  await image(page,'ancient').click(); await page.waitForURL('**/works/themes/ancient/');
  assert.equal(await page.locator('h1').innerText(),'远古地貌');
  assert.equal(await page.getByRole('link',{name:'查看作品详情 ↗',exact:true}).count(),1);
  await screenshot(page,'theme-ancient-1440'); record('island enters its own filtered work collection');
  await page.goBack(); await page.waitForURL('**/hub/'); await loaded(page); await waitIdle(page);
  assert.equal(await world(page).getAttribute('data-focused-island'),'ancient'); record('Back restores selected island');
  await page.mouse.move(20,820);
  const scenery = page.locator('[data-dynamic-background] > div').first();
  const before = await scenery.evaluate(n => getComputedStyle(n).transform);
  await page.waitForTimeout(400); const after = await scenery.evaluate(n => getComputedStyle(n).transform);
  assert.notEqual(before,after);
  await page.getByRole('button',{name:'暂停动态',exact:true}).click();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('[data-dynamic-background] > div')).animationPlayState === 'paused');
  const pausedA = await scenery.evaluate(n => getComputedStyle(n).transform);
  await page.waitForTimeout(250); const pausedB = await scenery.evaluate(n => getComputedStyle(n).transform);
  const matrixValues = value => value.match(/-?[\d.]+/g).map(Number);
  assert.ok(matrixValues(pausedA).every((v,i) => Math.abs(v - matrixValues(pausedB)[i]) < .01));
  record('background actually moves and pause freezes it');
  await page.getByRole('button',{name:'☀ DAY',exact:true}).click(); await page.reload({waitUntil:'networkidle'}); await loaded(page);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'day');
  await screenshot(page,'diamond-day-1440'); record('Day remains after reload');
  await desktop.close();
  for (const [width,height] of [[320,740],[390,844],[768,1024]]) {
    const context = await browser.newContext({ viewport:{width,height}, hasTouch:true, isMobile:width<=600 });
    const mobile = await context.newPage(); mobile.on('pageerror',error => errors.push(String(error)));
    await mobile.goto(origin + '/', {waitUntil:'networkidle'});
    assert.equal(await mobile.locator('canvas').count(),0); const welcomeLayout=await layout(mobile);
    const cb=await mobile.getByRole('button',{name:/^CONNECT/}).boundingBox();
    assert.ok(Math.abs(cb.x+cb.width/2-width/2)<2);
    await screenshot(mobile,'welcome-night-'+width);
    await mobile.goto(origin+'/hub/',{waitUntil:'networkidle'}); await loaded(mobile); await waitIdle(mobile);
    await screenshot(mobile,'diamond-night-'+width); const initialLayout=await layout(mobile);
    let center=await image(mobile,'sky').boundingBox();
    await mobile.touchscreen.tap(center.x+center.width*.5,center.y+center.height*.55);
    assert.match(mobile.url(),/\/hub\/$/);
    assert.equal(await world(mobile).getAttribute('data-touch-armed'),'sky');
    let side=await image(mobile,'home').boundingBox();
    await mobile.touchscreen.tap(side.x+side.width*.75,side.y+side.height*.5);
    await mobile.waitForFunction(() => document.querySelector('[data-focused-island]')?.dataset.focusedIsland==='home');
    assert.match(mobile.url(),/\/hub\/$/); await waitIdle(mobile);
    assert.equal(await world(mobile).getAttribute('data-touch-armed'),'home');
    center=await image(mobile,'home').boundingBox(); assert.ok(Math.abs(center.x+center.width/2-width/2)<2);
    await screenshot(mobile,'selected-home-'+width);
    await mobile.touchscreen.tap(center.x+center.width*.5,center.y+center.height*.55);
    await mobile.waitForURL('**/works/themes/home/');
    assert.equal(await mobile.locator('h1').innerText(),'二次元宅岛');
    await layout(mobile); await screenshot(mobile,'theme-home-'+width);
    record('touch first-select / second-enter '+width,{welcomeLayout,initialLayout});
    await context.close();
  }
  const reduced = await browser.newContext({viewport:{width:1440,height:900},reducedMotion:'reduce'});
  const quiet=await reduced.newPage(); await quiet.goto(origin+'/hub/',{waitUntil:'networkidle'}); await loaded(quiet);
  const animations=await quiet.locator('[data-dynamic-background] > div').evaluateAll(nodes=>nodes.map(n=>getComputedStyle(n).animationName));
  assert.ok(animations.every(n=>n==='none'));
  await image(quiet,'apocalypse').focus();
  await quiet.waitForFunction(()=>document.querySelector('[data-focused-island]')?.dataset.focusedIsland==='apocalypse');
  assert.equal(await world(quiet).getAttribute('data-moving'),'false');
  await image(quiet,'apocalypse').press('Enter'); await quiet.waitForURL('**/works/themes/apocalypse/');
  record('reduced-motion and keyboard direct entry'); await reduced.close();
  assert.deepEqual(errors,[]); record('no browser page errors');
  await writeFile(destination+'/checks.json',JSON.stringify({origin,checkedAt:new Date().toISOString(),browser:'Installed Microsoft Edge / isolated headless contexts',touch:'browser-emulated native touch; not a physical device',checks,errors},null,2)+'\n');
} finally { await browser.close(); }
