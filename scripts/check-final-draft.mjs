import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const origin = process.argv[2] || 'http://127.0.0.1:8080';
const destination = process.argv[3] || 'docs/agent-work/evidence/P2-r3/local';
await mkdir(destination, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-swiftshader'] });
const checks = [], errors = [];
const record = (name, detail = true) => { checks.push({ name, detail }); console.log('PASS ' + name); };
const capture = (page, name) => page.screenshot({ path: destination + '/' + name + '.png', fullPage: false });
const watch = page => page.on('pageerror', error => errors.push(String(error)));
const pose = async page => (await page.locator('canvas').getAttribute('data-pose')).split(',').map(Number);
const ready = page => page.waitForFunction(() => document.querySelector('[data-avatar-ready="true"] canvas[data-pose]'));
try {
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await desktop.newPage(); watch(page);
  await page.goto(origin + '/', { waitUntil: 'networkidle' });
  const connect = page.getByRole('button', { name: /^CONNECT/ });
  assert.equal(await page.locator('canvas').count(), 0);
  const samples = [];
  for (let i = 0; i < 8; i++) {
    samples.push(await connect.evaluate(n => Number(getComputedStyle(n).opacity)));
    await page.waitForTimeout(200);
  }
  assert.ok(Math.max(...samples) - Math.min(...samples) > .08);
  await capture(page, 'connect-night-1440');
  await connect.hover();
  assert.equal(await connect.evaluate(n => getComputedStyle(n).animationName), 'none');
  assert.equal(await connect.evaluate(n => getComputedStyle(n).opacity), '1');
  await page.mouse.move(10, 10);
  await connect.press('Tab');
  await page.keyboard.press('Shift+Tab');
  assert.ok(await connect.evaluate(n => n.matches(':focus-visible')));
  assert.equal(await connect.evaluate(n => getComputedStyle(n).animationName), 'none');
  record('CONNECT actually pulses; hover and focus stay steady', { opacitySamples: samples });
  await page.getByRole('button', { name: /DAY/ }).click();
  await page.mouse.move(10, 10);
  assert.notEqual(await connect.evaluate(n => getComputedStyle(n).animationName), 'none');
  await capture(page, 'connect-day-1440'); record('CONNECT pulse also enabled in Day');
  // Warm assets to measure the rig within the short greeting. Cold entrance and
  // its loading poster/automatic Hub transition are covered by world regression.
  await page.goto(origin + '/about/', { waitUntil: 'networkidle' }); await ready(page);
  await page.goto(origin + '/', { waitUntil: 'networkidle' });
  await connect.click(); await ready(page);
  assert.equal(await page.locator('[data-avatar-mode="idle"]').count(), 1);
  await page.mouse.move(1380, 180); await page.waitForTimeout(220);
  assert.deepEqual(await pose(page), [0, 0]);
  await page.mouse.move(60, 800); await page.waitForTimeout(220);
  assert.deepEqual(await pose(page), [0, 0]);
  await capture(page, 'greeting-idle-1440');
  await page.waitForURL('**/hub/', { timeout: 15000 });
  record('HELLO STRANGER avatar ignores pointer; still reaches Hub', { assetCache: 'Warmed via About; cold entry/loading poster verified separately by world regression' });
  await page.goto(origin + '/about/', { waitUntil: 'networkidle' }); await ready(page);
  assert.equal(await page.locator('[data-avatar-mode="pointer"]').count(), 1);
  await page.mouse.move(1296, 250);
  await page.waitForFunction(() => Number(document.querySelector('canvas').dataset.pose.split(',')[0]) > .65);
  const right = await pose(page);
  await capture(page, 'about-look-right-1440');
  await page.mouse.move(144, 750);
  await page.waitForFunction(() => Number(document.querySelector('canvas').dataset.pose.split(',')[0]) < -.65);
  const left = await pose(page);
  await capture(page, 'about-look-left-1440');
  assert.ok(right[1] < -.25 && left[1] > .25);
  record('About real 3D head and eyes follow across both axes', { right, left });
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await page.waitForFunction(() => document.querySelector('canvas')?.dataset.pose.split(',').every(value => Math.abs(Number(value)) < .005));
  await page.getByRole('button', { name: /PAPER MODE/ }).click();
  assert.equal(await page.locator('[data-paper="on"]').count(), 1);
  await ready(page); await capture(page, 'about-paper-1440');
  record('About returns gaze to center on blur; paper mode retains model');
  await desktop.close();
  for (const width of [320, 390]) {
    const touch = await browser.newContext({ viewport: { width, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
    const mobile = await touch.newPage(); watch(mobile);
    await mobile.goto(origin + '/about/', { waitUntil: 'networkidle' }); await ready(mobile);
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), width);
    await mobile.mouse.move(width - 10, 100); await mobile.waitForTimeout(250);
    assert.deepEqual(await pose(mobile), [0, 0]);
    await mobile.locator('[data-avatar-mode]').scrollIntoViewIfNeeded();
    await capture(mobile, 'about-touch-' + width);
    record('About touch ' + width + ' fits and does not simulate mouse gaze');
    await touch.close();
  }
  const reduced = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const quiet = await reduced.newPage(); watch(quiet);
  await quiet.goto(origin + '/', { waitUntil: 'networkidle' });
  assert.equal(await quiet.getByRole('button', { name: /^CONNECT/ }).evaluate(n => getComputedStyle(n).animationName), 'none');
  await quiet.goto(origin + '/about/', { waitUntil: 'networkidle' }); await ready(quiet);
  await quiet.mouse.move(1300, 180); await quiet.waitForTimeout(250);
  assert.deepEqual(await pose(quiet), [0, 0]);
  record('Reduced motion disables CONNECT pulse and About movement');
  await reduced.close();
  const fallback = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await fallback.route('**/media/avatar-proxy.glb', route => route.abort());
  const flat = await fallback.newPage(); watch(flat);
  await flat.goto(origin + '/about/', { waitUntil: 'networkidle' });
  await flat.getByText('轻量海报模式', { exact: true }).waitFor();
  assert.equal(await flat.locator('canvas').count(), 0);
  assert.ok(await flat.locator('img[src="/media/avatar-poster.png"]').isVisible());
  record('About model fetch failure shows readable poster fallback');
  await fallback.close();
  assert.deepEqual(errors, []); record('No page errors');
  await writeFile(destination + '/final-checks.json', JSON.stringify({ origin, checkedAt: new Date().toISOString(), browser: 'Installed Microsoft Edge / isolated headless contexts', touch: 'Browser emulation; not physical phones', checks, errors }, null, 2) + '\n');
} finally { await browser.close(); }
